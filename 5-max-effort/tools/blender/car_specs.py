"""Design specs of the 10 original player cars (silhouette profiles + details).

Axes: +Y forward, +X right, Z up, origin = ground under the wheelbase midpoint. All metres.
Profiles are (y, value) control points interpolated with a monotone cubic.
"""
import math

import bmesh
from mathutils import Matrix, Vector

import carkit
import kit_common as K


def _wheels(spec):
    wb = spec["wheelbase"] / 2.0
    spec["wheel_xy"] = [(spec["track_front"] / 2.0, wb), (spec["track_rear"] / 2.0, -wb)]
    spec.setdefault("wheel_radius_front", spec["wheel_radius"])
    spec.setdefault("wheel_radius_rear", spec["wheel_radius"])
    return spec


def door_lines(x, y_front, y_rear, z_bottom, z_top, sweep=0.06):
    """Vertical panel gaps of a door (front edge, rear edge) as projected strips."""
    return [
        {"kind": "strip", "name": "PanelGap_DoorFront", "mat": "Trim", "dir": (-1, 0, 0), "width": 0.005,
         "points": [(x, y_front - sweep, z_bottom), (x, y_front, (z_bottom + z_top) / 2), (x, y_front - 0.02, z_top)]},
        {"kind": "strip", "name": "PanelGap_DoorRear", "mat": "Trim", "dir": (-1, 0, 0), "width": 0.005,
         "points": [(x, y_rear, z_bottom), (x, y_rear - 0.01, (z_bottom + z_top) / 2), (x, y_rear + 0.04, z_top)]},
    ]


def gap(name, x, points):
    """Panel gap following [(y, z)] on the right side (mirrored)."""
    return {"kind": "strip", "name": name, "mat": "Trim", "dir": (-1, 0, 0), "width": 0.005,
            "points": [(x, y, z) for (y, z) in points]}


def top_pair(name, mat, center, size, shape="rect"):
    """Two patches projected from above (hood vents); projected_patch cannot mirror vertical casts."""
    a = {"kind": "patch", "name": name, "mat": mat, "center": center, "size": size, "shape": shape,
         "dir": (0, 0, -1), "mirror": False}
    b = dict(a)
    b["center"] = (-center[0], center[1], center[2])
    b["name"] = name + "_L"
    return [a, b]


def spare_wheel(center, radius, width, rim_ratio, rim_style="5spoke", spokes=5, tread="lug", rim_mat="RimDark"):
    """Extras: spare wheel on a tailgate carrier, face pointing backwards."""
    def build(spec, col, mats, proj, f):
        bm = carkit.build_tire(radius, width, radius * rim_ratio, 40, 0.016, tread)
        K.join_bm(bm, carkit.build_rim(radius * rim_ratio, width, rim_style, spokes), 1)
        bmesh.ops.rotate(bm, cent=(0, 0, 0), matrix=Matrix.Rotation(-math.pi / 2, 3, "Z"), verts=bm.verts)
        bmesh.ops.translate(bm, vec=center, verts=bm.verts)
        wheel = K.mesh_object("SpareWheel", bm, col, [mats["Rubber"], mats[rim_mat]])
        K.shade_auto(wheel, 32)
        cb = K.rounded_box_bm((0.32, 0.12, 0.08), (center[0], center[1] + width * 0.5 + 0.03, center[2]), 0.02, 2)
        carrier = K.mesh_object("SpareCarrier", cb, col, [mats["TrimMatte"]])
        return [wheel, carrier]
    return build


def roadster_screen(y_base, z_base, height, half_w, rake_deg, curve=0.07):
    """Extras: raked, wrap-around windscreen with a chrome frame (open cars)."""
    def build(spec, col, mats, proj, f):
        rows, cols = 4, 14
        rake = math.radians(rake_deg)
        bm = bmesh.new()
        grid = []
        for r in range(rows + 1):
            t = r / rows
            z = z_base + t * height * math.cos(rake)
            yb = y_base - t * height * math.sin(rake)
            row = []
            for c in range(cols + 1):
                u = -1.0 + 2.0 * c / cols
                row.append(bm.verts.new((u * half_w * (1.0 - 0.07 * t), yb - curve * u * u, z)))
            grid.append(row)
        for r in range(rows):
            for c in range(cols):
                bm.faces.new((grid[r][c], grid[r][c + 1], grid[r + 1][c + 1], grid[r + 1][c]))
        frame_pts = ([v.co.copy() for v in grid[rows]], [grid[r][0].co.copy() for r in range(rows + 1)],
                     [grid[r][cols].co.copy() for r in range(rows + 1)])
        glass = K.mesh_object("Glass_Windscreen", bm, col, [mats["Glass"]])
        fb = bmesh.new()
        for chain in frame_pts:
            for i in range(len(chain) - 1):
                carkit._segment_box(fb, chain[i], chain[i + 1], 0.018)
        frame = K.mesh_object("WindscreenFrame", fb, col, [mats["Chrome"]])
        K.shade_auto(frame, 40)
        return [glass, frame]
    return build


